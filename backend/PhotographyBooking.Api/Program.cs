        ALTER TABLE "StudioPortfolios" ADD COLUMN IF NOT EXISTS "Description" character varying(1000) NOT NULL DEFAULT '';
        ALTER TABLE "StudioPortfolios" ADD COLUMN IF NOT EXISTS "ImageUrl" character varying(2048) NOT NULL DEFAULT '';
        ALTER TABLE "StudioPortfolios" ADD COLUMN IF NOT EXISTS "Category" character varying(60) NOT NULL DEFAULT '';
        ALTER TABLE "StudioPortfolios" ADD COLUMN IF NOT EXISTS "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP;
        ALTER TABLE "StudioPortfolios" ADD COLUMN IF NOT EXISTS "UpdatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP;
        CREATE INDEX IF NOT EXISTS "IX_StudioPortfolios_StudioId" ON "StudioPortfolios" ("StudioId");

        CREATE TABLE IF NOT EXISTS "StudioServices" ("Id" uuid PRIMARY KEY);
        ALTER TABLE "StudioServices" ADD COLUMN IF NOT EXISTS "StudioId" uuid;
        ALTER TABLE "StudioServices" ADD COLUMN IF NOT EXISTS "ServiceName" character varying(160) NOT NULL DEFAULT '';
        ALTER TABLE "StudioServices" ADD COLUMN IF NOT EXISTS "Description" character varying(1000) NOT NULL DEFAULT '';
        ALTER TABLE "StudioServices" ADD COLUMN IF NOT EXISTS "PackageDetails" text[] NOT NULL DEFAULT ARRAY[]::text[];
        ALTER TABLE "StudioServices" ADD COLUMN IF NOT EXISTS "StartingPrice" numeric(12,2) NOT NULL DEFAULT 0;
