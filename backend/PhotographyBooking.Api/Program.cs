        ALTER TABLE "StudioAvailabilities" ADD COLUMN IF NOT EXISTS "Date" date NOT NULL DEFAULT CURRENT_DATE;
        ALTER TABLE "StudioAvailabilities" ADD COLUMN IF NOT EXISTS "IsAvailable" boolean NOT NULL DEFAULT false;
        ALTER TABLE "StudioAvailabilities" ADD COLUMN IF NOT EXISTS "StartTime" time without time zone;
        ALTER TABLE "StudioAvailabilities" ADD COLUMN IF NOT EXISTS "EndTime" time without time zone;
        ALTER TABLE "StudioAvailabilities" ADD COLUMN IF NOT EXISTS "Notes" character varying(1000);
