        ALTER TABLE "Studios" ADD COLUMN IF NOT EXISTS "Email" character varying(254) NOT NULL DEFAULT '';
        ALTER TABLE "Studios" ADD COLUMN IF NOT EXISTS "ExperienceYears" integer NOT NULL DEFAULT 0;
        ALTER TABLE "Studios" ADD COLUMN IF NOT EXISTS "PhotographyTypes" character varying(500) NOT NULL DEFAULT '';
        ALTER TABLE "Studios" ADD COLUMN IF NOT EXISTS "StartingPrice" numeric(12,2) NOT NULL DEFAULT 0;
        ALTER TABLE "Studios" ADD COLUMN IF NOT EXISTS "LogoUrl" character varying(2048) NOT NULL DEFAULT '';
        ALTER TABLE "Studios" ADD COLUMN IF NOT EXISTS "CoverPhotoUrl" character varying(2048) NOT NULL DEFAULT '';
        ALTER TABLE "Studios" ADD COLUMN IF NOT EXISTS "ProfileImage" character varying(2048) NOT NULL DEFAULT '';
        UPDATE "Studios" SET "LogoUrl" = "ProfileImage" WHERE "LogoUrl" = '' AND "ProfileImage" <> '';
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_Studios_UserId" ON "Studios" ("UserId") WHERE "UserId" IS NOT NULL;

        CREATE TABLE IF NOT EXISTS "StudioPortfolios" ("Id" uuid PRIMARY KEY);
        ALTER TABLE "StudioPortfolios" ADD COLUMN IF NOT EXISTS "StudioId" uuid;
